"""Paper Table 8, HHL and LuGo columns, constructed and transpiled under
qiskit 2.6.

HHL: the fvm solver's own step-0 circuit, built as solve_one_step builds it
(scale_Ab, convert_to_pow2, convert_system_to_herm, then
QuantumHHL.generate_circuit) from the saved step-0 system, with the solver
venv's qiskit and quantum_linear_solvers. Nothing is simulated.
LuGo: ORNL's 2026-11-03 rerun (generated by qiskit 2.6.1), loaded with the
1/x parameters read from the feb26 circuit, as run_step0.py does.

Before any transpile, the QPE block matrices of the two circuits are
compared with each other and with those of the qiskit 1.2.4 base HHL that
the table used before: equal blocks mean the same system and the same
solution, so the recorded solution fidelity carries over. Then each circuit
is transpiled as table 8 is: level 2, seed_transpiler 1, to all-to-all
cx/rz/sx/x, FakeMarrakesh and FakeNighthawk.

Run with the fvm solver venv. Usage:
  table8_columns.py [--targets a2a,heron,nighthawk] [--out DIR]
"""
import argparse
import csv
import json
import pickle
import sys
import time
from pathlib import Path

import numpy as np
import qiskit
from qiskit import qpy
from qiskit.transpiler import generate_preset_pass_manager
from qiskit_ibm_runtime.fake_provider import FakeMarrakesh, FakeNighthawk

HERE = Path(__file__).resolve().parent
EXP = HERE.parents[2]
FVM = HERE.parents[3] / "fvm_euler_1d_solver"
RES = EXP / "results" / "fvm_euler_1d_solver"
NOV25 = RES / "nov2025-rerun/nov_pkgs/2026-11-03/_9f0fbf67/719a35aa"
LUGO_NOV = RES / "nov2025-rerun/LuGo-rerun/circuits"
LUGO_FEB = RES / "2026-02-26-LuGo/circuits"
sys.path[:0] = [str(FVM), str(HERE), str(HERE.parent / "lugo-qpy-rewrite-2026-11")]
import quantum_tools as qt  # noqa: E402
from math_tools import (convert_system_to_herm, convert_to_pow2,  # noqa: E402
                        scale_Ab)
import structured_rewrite as sr  # noqa: E402
from qpy_rewrite import load_qpy, recip_params  # noqa: E402


def build_hhl(out: Path) -> qiskit.QuantumCircuit:
    with open(NOV25 / "system_Ab_nelem5_iter0.pkl", "rb") as fh:
        ab = pickle.load(fh)
    qh = qt.QuantumHHL(verbosity=0, output_dir=str(out))
    qh.savedata = False
    a, b, _, _ = scale_Ab(ab["A"], ab["b"], verbosity=0)
    a2, b2 = convert_to_pow2(a, b, verbosity=0, eps=qh.pad_eps,
                             spectral_diag=qh.spectral_diag)
    ah, bh = convert_system_to_herm(a2, b2, eps=qh.pad_eps, verbosity=0,
                                    spectral_diag=qh.spectral_diag)
    t0 = time.time()
    circ, _ = qh.generate_circuit(ah, bh, 5, step=0, iter=0, deflate_k=0,
                                  spectrum=None)
    print(f"HHL built in {time.time() - t0:.1f} s", flush=True)
    with open(out / "hhl_qiskit26_nelem5_iter0.qpy", "wb") as fh:
        qpy.dump(circ, fh)
    return circ


def blocks(circ: qiskit.QuantumCircuit) -> list[np.ndarray]:
    """QPE block matrices via structured_rewrite.walk. qiskit 2.x names the
    reciprocal 'ExactReciprocal' where walk looks for '1/x', so a renamed
    copy of the circuit is walked; the circuit itself is not changed."""
    c = circ.remove_final_measurements(inplace=False)
    named = c.copy_empty_like()
    for ins in c.data:
        op = ins.operation
        if op.name == "ExactReciprocal":
            op = op.copy()
            op.name = "1/x"
        named.append(op, ins.qubits, ins.clbits)
    items, _, _ = sr.walk(named)
    return sr.block_unitaries(items)


def counts(circ: qiskit.QuantumCircuit, target: str) -> dict:
    kw = ({"basis_gates": ["cx", "rz", "sx", "x"]} if target == "a2a" else
          {"backend": FakeMarrakesh() if target == "heron"
           else FakeNighthawk()})
    pm = generate_preset_pass_manager(optimization_level=2, seed_transpiler=1,
                                      **kw)
    t0 = time.time()
    t = pm.run(circ.remove_final_measurements(inplace=False))
    return {"target": target,
            "two_qubit_gates": sum(1 for i in t.data
                                   if i.operation.num_qubits == 2),
            "two_qubit_depth": t.depth(lambda i: i.operation.num_qubits == 2),
            "depth": t.depth(), "transpile_s": round(time.time() - t0, 1)}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--targets", default="a2a,heron,nighthawk")
    ap.add_argument("--out", type=Path, default=Path.home() / "q8020/table8")
    a = ap.parse_args()
    a.out.mkdir(parents=True, exist_ok=True)
    print("qiskit", qiskit.__version__, flush=True)
    hhl = build_hhl(a.out)
    feb = load_qpy(str(LUGO_FEB / "circuit_generated_nelem5_iter0.qpy"))
    lugo = load_qpy(str(LUGO_NOV / "circuit_generated_statevector_nelem5_iter0.qpy"),
                    recip=recip_params(feb))
    old = load_qpy(str(NOV25 / "circuit_generated_statevector_nelem5_iter0.qpy"))
    mh, ml, mo = blocks(hhl), blocks(lugo), blocks(old)
    check = {"blocks": [len(mh), len(ml), len(mo)],
             "max_diff_hhl26_vs_lugo_nov26": max(
                 float(np.max(np.abs(x - y))) for x, y in zip(mh, ml)),
             "max_diff_hhl26_vs_hhl_qiskit124": max(
                 float(np.max(np.abs(x - y))) for x, y in zip(mh, mo))}
    print(json.dumps(check), flush=True)
    rows = []
    for name, circ in (("lugo_nov26", lugo), ("hhl_qiskit26", hhl)):
        for tgt in [t for t in a.targets.split(",") if t]:
            row = {"circuit": name, **counts(circ, tgt)}
            rows.append(row)
            print(row, flush=True)
            with open(a.out / "table8_columns.csv", "w", newline="") as fh:
                w = csv.DictWriter(fh, fieldnames=list(rows[0]))
                w.writeheader()
                w.writerows(rows)
    (a.out / "table8_check.json").write_text(json.dumps(check, indent=1) + "\n")


if __name__ == "__main__":
    main()
